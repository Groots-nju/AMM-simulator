import { resolveArtifactUrl, type PlotLink, type SimulationResponse } from "../lib/api";

type PlotGalleryProps = {
  result: SimulationResponse | null;
};

function toDisplayTitle(plotName: string): string {
  return plotName
    .split("_")
    .map((segment) => segment.charAt(0).toUpperCase() + segment.slice(1))
    .join(" ");
}

function getPlotDescription(plotName: string): string {
  if (plotName === "spot_price_series") {
    return "How the pool-implied spot price changes across simulation steps.";
  }
  if (plotName === "lp_vs_hodl") {
    return "Comparison between LP portfolio value and simple HODL value.";
  }
  return "Simulation artifact generated by the backend.";
}

export function PlotGallery({ result }: PlotGalleryProps) {
  if (!result) {
    return (
      <section className="panel">
        <h2 className="summary-heading">Generated Plots</h2>
        <p className="summary-empty">
          Run a scenario to generate backend plot artifacts and display them here.
        </p>
      </section>
    );
  }

  if (result.plots.length === 0) {
    return (
      <section className="panel">
        <h2 className="summary-heading">Generated Plots</h2>
        <p className="summary-empty">This scenario did not produce any plot artifacts.</p>
      </section>
    );
  }

  return (
    <section className="panel">
      <h2 className="summary-heading">Generated Plots</h2>
      <div className="plot-grid">
        {result.plots.map((plot: PlotLink) => (
          <article className="plot-card" key={plot.url}>
            <div className="plot-card-header">
              <div>
                <h3 className="plot-title">{toDisplayTitle(plot.name)}</h3>
                <p className="plot-caption">{getPlotDescription(plot.name)}</p>
              </div>
              <a
                className="plot-link"
                href={resolveArtifactUrl(plot.url)}
                target="_blank"
                rel="noreferrer"
              >
                Open Image
              </a>
            </div>
            <img
              className="plot-image"
              src={resolveArtifactUrl(plot.url)}
              alt={toDisplayTitle(plot.name)}
            />
          </article>
        ))}
      </div>
    </section>
  );
}
